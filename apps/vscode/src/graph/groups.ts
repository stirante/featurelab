/** Folds each collapsed group into ONE synthetic node, edges re-pointed.
 *
 * The same shape webview/graph.ts's collapseCompounds has, for the same reasons: an edge that
 * leaves or enters a hidden member is KEPT and re-pointed at the card that now stands for it,
 * because those edges are the shape of the pack and the reason to collapse anything is to see
 * that shape; several members reaching the same outside node become one edge, since drawn four
 * times it is four arrowheads on one line; and an edge between two members of one group is
 * dropped, because a self-loop on a card would draw the inside as a decoration on the outside.
 *
 * The synthetic node is inserted where the group's first member was, so draw order -- and with it
 * which card lands on top when two overlap -- stays where the author would expect. It carries
 * `group` so the renderer can draw it from the node alone. Roots are kept for every node still
 * drawn, and a group card is a root when one of its members was and nothing outside now reaches
 * it -- the second half matters, because "starts here" on a card something points at is wrong.
 *
 * Expanded groups change nothing here: their members are drawn as themselves, inside a frame the
 * renderer draws from `expandedFrames`. */
export function collapseGroups<
  N extends { readonly id: string },
  E extends GroupEdgeWire,
  G extends { readonly nodes: readonly N[]; readonly edges: readonly E[]; readonly roots: readonly string[] },
>(graph: G, view: GroupsView): G {
  const collapsed = view.groups.filter((g) => g.collapsed)
  if (collapsed.length === 0) return graph
  const present = new Set(graph.nodes.map((n) => n.id))
  const ownerOf = new Map<string, string>()
  const firstMember = new Map<string, string>()
  for (const group of collapsed) {
    for (const member of group.memberIds) {
      if (!present.has(member)) continue
      ownerOf.set(member, groupNodeId(group.id))
      if (!firstMember.has(group.id)) firstMember.set(group.id, member)
    }
  }
  if (ownerOf.size === 0) return graph

  const nodes: N[] = []
  for (const node of graph.nodes) {
    const owner = ownerOf.get(node.id)
    if (owner === undefined) {
      nodes.push(node)
      continue
    }
    const group = collapsed.find((g) => groupNodeId(g.id) === owner)
    if (group !== undefined && firstMember.get(group.id) === node.id) {
      const count = group.memberIds.filter((id) => present.has(id)).length
      const summary: GroupNodeSummary = { id: group.id, name: group.name, count }
      nodes.push({ id: owner, group: summary } as unknown as N)
    }
  }

  const edges: E[] = []
  const seen = new Set<string>()
  const entered = new Set<string>()
  for (const edge of graph.edges) {
    const from = ownerOf.get(edge.from) ?? edge.from
    const to = ownerOf.get(edge.to) ?? edge.to
    const touched = from !== edge.from || to !== edge.to
    if (touched && from === to) continue
    if (touched) {
      const key = `${from} ${to} ${edge.kind}`
      if (seen.has(key)) continue
      seen.add(key)
    }
    if (ownerOf.has(edge.to)) entered.add(to)
    edges.push(touched ? { ...edge, from, to } : edge)
  }

  const roots: string[] = []
  const rootSet = new Set(graph.roots)
  const groupRooted = new Set<string>()
  for (const id of graph.roots) {
    const owner = ownerOf.get(id)
    if (owner === undefined) roots.push(id)
    else if (!entered.has(owner)) groupRooted.add(owner)
  }
  for (const node of nodes) {
    if (groupRooted.has(node.id) && !rootSet.has(node.id)) roots.push(node.id)
  }

  return { ...graph, nodes, edges, roots }
}

/** Where each collapsed group's card goes: the top-left of its members' positions, so the card
 * sits where the group was rather than wherever an automatic layout would put a node nobody
 * placed. Members with no position contribute nothing; a group none of whose members has one gets
 * no entry, and the renderer's own fallback places it. */
export function groupCardPositions(
  view: GroupsView,
  positions: ReadonlyMap<string, { readonly x: number; readonly y: number }>,
): Map<string, { x: number; y: number }> {
  const out = new Map<string, { x: number; y: number }>()
  for (const group of view.groups) {
    if (!group.collapsed) continue
    let x = Infinity
    let y = Infinity
    for (const id of group.memberIds) {
      const at = positions.get(id)
      if (!at) continue
      x = Math.min(x, at.x)
      y = Math.min(y, at.y)
    }
    if (Number.isFinite(x) && Number.isFinite(y)) out.set(groupNodeId(group.id), { x, y })
  }
  return out
}

/** The frames the renderer draws for EXPANDED groups: which members, under what name. Only the
 * members actually in `graph`, so a frame is never drawn around a node that is not there. */
export function expandedFrames(view: GroupsView, graph: { readonly nodes: readonly { readonly id: string }[] }): { groupId: string; name: string; memberIds: string[] }[] {
  const present = new Set(graph.nodes.map((n) => n.id))
  const out: { groupId: string; name: string; memberIds: string[] }[] = []
  for (const group of view.groups) {
    if (group.collapsed) continue
    const memberIds = group.memberIds.filter((id) => present.has(id))
    if (memberIds.length === 0) continue
    out.push({ groupId: group.id, name: group.name, memberIds })
  }
  return out
}
