export interface FeatureGroup {
  readonly id: string
  readonly name: string
  readonly collapsed: boolean
  /** In graph order. Never empty: a group with no members is not a group, it is the absence of
   * one, and `readGroups` never returns it. */
  readonly memberIds: readonly string[]
  /** Disagreements between members, one line each, for the panel to show as notes. */
  readonly warnings: readonly string[]
}

export interface GroupsView {
  /** In order of first appearance in the graph. */
  readonly groups: readonly FeatureGroup[]
  readonly byId: ReadonlyMap<string, FeatureGroup>
  /** Node id -> the id of the group it belongs to. */
  readonly memberOf: ReadonlyMap<string, string>
  /** Directives that could not be read as a group at all, one line each. */
  readonly warnings: readonly string[]
}

const EMPTY_VIEW: GroupsView = { groups: [], byId: new Map(), memberOf: new Map(), warnings: [] }

interface ParsedDirective {
  readonly id: string
  readonly collapsed: boolean
  readonly name: string
}

/** Reads one directive's arguments, or says why they are not a group. */
function parseDirective(args: readonly string[] | undefined): { ok: true; value: ParsedDirective } | { ok: false; why: string } {
  const list = args ?? []
  const id = list[0]
  const state = list[1]
  if (id === undefined || state === undefined || list.length < 3) {
    return { ok: false, why: 'it needs an id, a state and a name' }
  }
  if (!GROUP_ID_PATTERN.test(id)) return { ok: false, why: `"${id}" is not a group id (letters, digits, - and _ only)` }
  if (state !== 'expanded' && state !== 'collapsed') return { ok: false, why: `"${state}" is neither expanded nor collapsed` }
  const name = normaliseGroupName(list.slice(2).join(' '))
  if (name === '') return { ok: false, why: 'the name is empty' }
  return { ok: true, value: { id, collapsed: state === 'collapsed', name } }
}

/** The commonest value in a list, ties to the first seen, and whether there was any disagreement. */
function majority<T>(values: readonly T[], describe: (v: T) => string): { value: T; note: string | null } {
  const counts = new Map<T, number>()
  for (const v of values) counts.set(v, (counts.get(v) ?? 0) + 1)
  let best: T = values[0] as T
  let bestCount = 0
  for (const [v, n] of counts) {
    if (n > bestCount) {
      best = v
      bestCount = n
    }
  }
  if (counts.size <= 1) return { value: best, note: null }
  const parts = [...counts.entries()].map(([v, n]) => `${describe(v)} ×${String(n)}`)
  return { value: best, note: parts.join(', ') }
}

/** Every group the graph's files declare.
 *
 * Read from the nodes as handed in, so a caller that has already hidden a compound's children
 * gets groups without those children -- a node that is not drawn cannot be a member of anything
 * drawn. Nodes with no file carry no annotations and so are never members. */
export function readGroups(graph: GroupGraph): GroupsView {
  const members = new Map<string, { node: GroupNodeWire; directive: ParsedDirective }[]>()
  const order: string[] = []
  const warnings: string[] = []
  const perGroupWarnings = new Map<string, string[]>()

  for (const node of graph.nodes) {
    if (!node.file) continue
    const directives = (node.annotations ?? []).filter((a) => a.name === GROUP_DIRECTIVE && a.jsonPath === '$')
    const first = directives[0]
    if (first === undefined) continue
    const parsed = parseDirective(first.args)
    if (!parsed.ok) {
      warnings.push(`${node.id}: its @featurelab:group directive was ignored -- ${parsed.why}.`)
      continue
    }
    const id = parsed.value.id
    if (!members.has(id)) {
      members.set(id, [])
      order.push(id)
    }
    members.get(id)!.push({ node, directive: parsed.value })
    if (directives.length > 1) {
      const list = perGroupWarnings.get(id) ?? []
      list.push(`${node.id} carries ${String(directives.length)} group directives; the first one is used.`)
      perGroupWarnings.set(id, list)
    }
  }
  if (order.length === 0 && warnings.length === 0) return EMPTY_VIEW

  const groups: FeatureGroup[] = []
  const byId = new Map<string, FeatureGroup>()
  const memberOf = new Map<string, string>()
  for (const id of order) {
    const list = members.get(id)!
    const name = majority(list.map((m) => m.directive.name), (v) => `"${v}"`)
    const state = majority(list.map((m) => m.directive.collapsed), (v) => (v ? 'collapsed' : 'expanded'))
    const notes = [...(perGroupWarnings.get(id) ?? [])]
    if (name.note !== null) notes.push(`Members disagree about the name (${name.note}); showing the commoner one. Renaming fixes all of them.`)
    if (state.note !== null) notes.push(`Members disagree about being collapsed (${state.note}); showing the commoner state. Collapsing or expanding fixes all of them.`)
    const group: FeatureGroup = {
      id,
      name: name.value,
      collapsed: state.value,
      memberIds: list.map((m) => m.node.id),
      warnings: notes,
    }
    groups.push(group)
    byId.set(id, group)
    for (const m of list) memberOf.set(m.node.id, id)
  }
  return { groups, byId, memberOf, warnings }
}

/** The group a node belongs to, or null. */
export function groupOf(view: GroupsView, nodeId: string): FeatureGroup | null {
  const id = view.memberOf.get(nodeId)
  return id === undefined ? null : (view.byId.get(id) ?? null)
}

