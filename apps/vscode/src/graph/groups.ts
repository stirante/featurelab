/** Why a node cannot be a member, or null when it can.
 *
 * Only a node with a real file can carry the directive, so only a node with a real file can be a
 * member: not a dangling reference, not one of the game's own features, not the synthetic card
 * of another group. A hidden child of a collapsed compound is not in the graph this module is
 * handed, so it never reaches here -- and that is right: the compound stands for it. */
export function groupableReason(node: GroupNodeWire): string | null {
  if (isGroupNodeId(node.id)) return `${node.id} is a group, and groups do not nest.`
  if (node.external) return `${node.id} is provided by the game, and there is no file here to record a group on.`
  if (node.unresolved) return `${node.id} is not defined in this pack, so there is no file to record a group on.`
  if (!node.file) return `${node.id} has no file behind it.`
  return null
}

