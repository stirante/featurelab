/** One step of the engine's `annotateBatch`: the same three coordinates `annotate` takes, plus
 * `remove`, which takes the directive OUT instead of writing it. Spelled here, in the one module
 * that plans them, so the host relays them without re-shaping. */
export interface AnnotateOp {
  /** Pack-relative, as wire.GraphNode.File reports it. */
  readonly file: string
  /** What the directive is about, in jsonc.FormatPath's dialect; `$` for the file itself. */
  readonly path: string
  readonly name: string
  readonly args?: readonly string[]
  readonly remove?: boolean
}

/** The slice of wire.Annotation this module reads. */
export interface GroupAnnotationWire {
  readonly name: string
  readonly args?: readonly string[]
  readonly jsonPath: string
}

/** The slice of wire.GraphNode this module reads. */
export interface GroupNodeWire {
  readonly id: string
  readonly file?: string
  readonly unresolved?: boolean
  readonly external?: boolean
  readonly annotations?: readonly GroupAnnotationWire[]
}

export interface GroupEdgeWire {
  readonly from: string
  readonly to: string
  readonly kind: string
}

export interface GroupGraph {
  readonly nodes: readonly GroupNodeWire[]
  readonly edges: readonly GroupEdgeWire[]
  readonly roots: readonly string[]
}

/** What the renderer is handed on a collapsed group's synthetic node, so it can draw the card
 * from the node alone. Mirrored by render.ts's GraphNodeGroupWire. */
export interface GroupNodeSummary {
  readonly id: string
  readonly name: string
  readonly count: number
}

