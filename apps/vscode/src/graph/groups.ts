export type GroupPlan =
  | {
      readonly ok: true
      readonly ops: readonly AnnotateOp[]
      /** One line for the status bar. */
      readonly summary: string
      readonly groupId: string
      /** Nodes this takes OUT of another group on the way in. */
      readonly moved: readonly string[]
    }
  | { readonly ok: false; readonly reason: string }

function refuse(reason: string): GroupPlan {
  return { ok: false, reason }
}

function setOp(file: string, id: string, collapsed: boolean, name: string): AnnotateOp {
  return { file, path: '$', name: GROUP_DIRECTIVE, args: [id, collapsed ? 'collapsed' : 'expanded', ...nameWords(name)] }
}

function removeOp(file: string): AnnotateOp {
  return { file, path: '$', name: GROUP_DIRECTIVE, remove: true }
}

/** The nodes named, with their files, or the first reason one of them cannot be a member. */
function membersFor(graph: GroupGraph, nodeIds: readonly string[]): { ok: true; nodes: (GroupNodeWire & { file: string })[] } | { ok: false; reason: string } {
  const byId = new Map(graph.nodes.map((n) => [n.id, n]))
  const out: (GroupNodeWire & { file: string })[] = []
  const seen = new Set<string>()
  for (const id of nodeIds) {
    if (seen.has(id)) continue
    seen.add(id)
    const node = byId.get(id)
    if (node === undefined) return { ok: false, reason: `${id} is not in the graph.` }
    const why = groupableReason(node)
    if (why !== null) return { ok: false, reason: why }
    out.push(node as GroupNodeWire & { file: string })
  }
  return { ok: true, nodes: out }
}

function plural(n: number, word: string): string {
  return `${String(n)} ${word}${n === 1 ? '' : 's'}`
}

/** A new group of `nodeIds`, expanded, called `name`. Nodes already in another group are moved:
 * their directive is REWRITTEN rather than removed and re-added, since one file carries one. */
export function planCreate(graph: GroupGraph, view: GroupsView, nodeIds: readonly string[], name: string): GroupPlan {
  const problem = validateGroupName(name)
  if (problem !== null) return refuse(problem)
  if (nodeIds.length === 0) return refuse('Select at least one feature to group.')
  const members = membersFor(graph, nodeIds)
  if (!members.ok) return refuse(members.reason)
  const clean = normaliseGroupName(name)
  const id = slugForGroup(clean, view.byId.keys())
  const moved = members.nodes.filter((n) => view.memberOf.has(n.id)).map((n) => n.id)
  return {
    ok: true,
    ops: members.nodes.map((n) => setOp(n.file, id, false, clean)),
    summary: `Grouping ${plural(members.nodes.length, 'feature')} as "${clean}".`,
    groupId: id,
    moved,
  }
}

/** Every member rewritten with the new name; the id and the state stay. */
export function planRename(graph: GroupGraph, view: GroupsView, groupId: string, name: string): GroupPlan {
  const group = view.byId.get(groupId)
  if (group === undefined) return refuse(`There is no group ${groupId}.`)
  const problem = validateGroupName(name)
  if (problem !== null) return refuse(problem)
  const clean = normaliseGroupName(name)
  const members = membersFor(graph, group.memberIds)
  if (!members.ok) return refuse(members.reason)
  return {
    ok: true,
    ops: members.nodes.map((n) => setOp(n.file, group.id, group.collapsed, clean)),
    summary: `Renaming "${group.name}" to "${clean}".`,
    groupId: group.id,
    moved: [],
  }
}

/** Every member rewritten with the new state. Also the repair for members that disagree. */
export function planSetCollapsed(graph: GroupGraph, view: GroupsView, groupId: string, collapsed: boolean): GroupPlan {
  const group = view.byId.get(groupId)
  if (group === undefined) return refuse(`There is no group ${groupId}.`)
  const members = membersFor(graph, group.memberIds)
  if (!members.ok) return refuse(members.reason)
  return {
    ok: true,
    ops: members.nodes.map((n) => setOp(n.file, group.id, collapsed, group.name)),
    summary: `${collapsed ? 'Collapsing' : 'Expanding'} "${group.name}".`,
    groupId: group.id,
    moved: [],
  }
}

/** Adds `nodeIds` to an existing group. A node already in it is left alone; one in another group
 * is moved, which is one rewrite of its directive. */
export function planAdd(graph: GroupGraph, view: GroupsView, groupId: string, nodeIds: readonly string[]): GroupPlan {
  const group = view.byId.get(groupId)
  if (group === undefined) return refuse(`There is no group ${groupId}.`)
  const incoming = nodeIds.filter((id) => view.memberOf.get(id) !== group.id)
  if (incoming.length === 0) return refuse(`Already in "${group.name}".`)
  const members = membersFor(graph, incoming)
  if (!members.ok) return refuse(members.reason)
  const moved = members.nodes.filter((n) => view.memberOf.has(n.id)).map((n) => n.id)
  return {
    ok: true,
    ops: members.nodes.map((n) => setOp(n.file, group.id, group.collapsed, group.name)),
    summary: `Adding ${plural(members.nodes.length, 'feature')} to "${group.name}".`,
    groupId: group.id,
    moved,
  }
}

/** Takes `nodeIds` out of a group. Removing the last member removes the group, because the group
 * IS its members' directives and nothing else. */
export function planRemove(graph: GroupGraph, view: GroupsView, groupId: string, nodeIds: readonly string[]): GroupPlan {
  const group = view.byId.get(groupId)
  if (group === undefined) return refuse(`There is no group ${groupId}.`)
  const leaving = nodeIds.filter((id) => view.memberOf.get(id) === group.id)
  if (leaving.length === 0) return refuse(`None of those are in "${group.name}".`)
  const members = membersFor(graph, leaving)
  if (!members.ok) return refuse(members.reason)
  const last = leaving.length >= group.memberIds.length
  return {
    ok: true,
    ops: members.nodes.map((n) => removeOp(n.file)),
    summary: last
      ? `Removing the last of "${group.name}", which ends the group.`
      : `Removing ${plural(members.nodes.length, 'feature')} from "${group.name}".`,
    groupId: group.id,
    moved: [],
  }
}

/** Dissolves a group: every member's directive removed, every feature left exactly where it is. */
export function planUngroup(graph: GroupGraph, view: GroupsView, groupId: string): GroupPlan {
  const group = view.byId.get(groupId)
  if (group === undefined) return refuse(`There is no group ${groupId}.`)
  const members = membersFor(graph, group.memberIds)
  if (!members.ok) return refuse(members.reason)
  return {
    ok: true,
    ops: members.nodes.map((n) => removeOp(n.file)),
    summary: `Ungrouping "${group.name}" -- ${plural(members.nodes.length, 'feature')} stay where they are.`,
    groupId: group.id,
    moved: [],
  }
}

