// groups.ts -- author-declared groups of features, read from and written to the pack files.
//
// A group is PRESENTATION THE AUTHOR DECLARED: several features and rules the author decided to
// look at as one thing, with a name, and either spread out inside a frame or folded into one
// card. That is the whole of it. A group has no meaning to the game and no meaning to the engine;
// it is what a person thinks a pack is made of, written down so the next person opening the pack
// sees the same shape.
//
// Three decisions follow from that, and each rules something out:
//
//   - MEMBERSHIP, NAME AND STATE LIVE IN THE PACK FILES, as a `@featurelab:group` directive in a
//     comment on each member's root. Not in the per-user layout sidecar: a group is a statement
//     about the pack, and a statement kept where only one person can see it is a note to self,
//     not a shape. So collapsing a group -- which is also a statement, "these read as one" --
//     rewrites its members' files, and is committed with the pack like everything else in it.
//   - A GROUP IS NEVER INFERRED. Nothing here looks at names, directories or delegations and
//     decides that some features belong together. The only groups are the ones written down.
//   - EDITING A MEMBER CHANGES NOTHING ABOUT THE GROUP. This is the difference from a compound
//     (compounds/collapse.ts), whose files are GENERATED from its parameters and which therefore
//     ejects to plain nodes the moment one of them is edited by hand. A group's members were never
//     generated by anything; the directive is a label, and a label survives any edit to the thing
//     it is on.
//
// # The directive
//
//   // @featurelab:group <id> <expanded|collapsed> <name words...>
//
// on the ROOT of each member's file (JSONPath `$`). The id is a slug ([a-z0-9_-]+) derived from
// the name when the group is made and kept stable across renames, so a rename rewrites the name
// words and nothing else -- and so two groups can share a display name without becoming one. The
// state and the name are repeated in every member because there is no other file to put them in:
// a pack has no manifest of groups, and inventing one would be a file the engine has to skip and
// an author has to keep in step with N others.
//
// Repetition means members CAN disagree, and `readGroups` says what happens then: the commonest
// value wins, the disagreement is reported on the group, and nothing is silently rewritten. Two
// files that disagree about a name is a state somebody produced by editing a comment in a text
// editor, which is legitimate, and the editor's job is to show it and offer the fix, not to pick
// a side and overwrite the other.
//
// # Flat
//
// A feature belongs to at most one group and a group holds no groups. One directive per file is
// what makes the first true (a file with two is reported and the first is used); the second is
// simply not expressible in the directive, and that is deliberate -- nested groups are a tree
// editor's worth of interaction over a canvas whose whole difficulty is already density.
//
// # What this module does not do
//
// It never touches a file and never draws. `plan*` return the batch of directive writes and
// removals that an operation means, in the shape the engine's `annotateBatch` takes, and the
// webview posts them; `collapseGroups` returns a view graph and the renderer draws it. Both
// halves are pure so both are testable without a browser or an engine.

/** The directive's name, without the `@featurelab:` prefix. */
export const GROUP_DIRECTIVE = 'group'

/** The id prefix of the synthetic node a collapsed group draws as. Chosen so it cannot collide
 * with a feature identifier, which always carries a namespace and a colon after it -- `group:` IS
 * a namespace-shaped prefix, and a pack could in principle own it, so the check is stricter than
 * the prefix: see isGroupNodeId. */
export const GROUP_NODE_PREFIX = 'group:'

/** What a group id may look like. Lower-case, so a slug derived from any name is one. */
const GROUP_ID_PATTERN = /^[a-z0-9_-]+$/

/** Whether two directive names are the same directive.
 *
 * FOLD-INSENSITIVE, because the engine's own suppression already is: `suppressedByIgnore` in
 * wire/graphcheck.go matches `@featurelab:ignore` with `strings.EqualFold`, so one half of this
 * tool honoured a capital and the other half dropped it. `@featurelab:Group pumpkins expanded
 * Pumpkins` drew no group, warned nowhere, and read in the file exactly like one that worked --
 * which is the same silence a misplaced directive produces, arrived at from the other side.
 *
 * Recognising it is not the same as approving of it: readGroups reports the spelling, because
 * only the exact lower-case name survives a round trip through the engine's own writer. */
function sameDirectiveName(a: string, b: string): boolean {
  return a.toLowerCase() === b.toLowerCase()
}

/** Whether an annotation is a `@featurelab:group` directive, at any path and in any case. */
function isGroupDirective(a: GroupAnnotationWire): boolean {
  return sameDirectiveName(a.name, GROUP_DIRECTIVE)
}

/** Every group directive a node's file carries -- ROOT OR NOT, and however it is spelled.
 *
 * The one list that answers "how many of these are in this file", which is what both the removal
 * plan and the warnings need and what neither of them had: both used to filter on `jsonPath ===
 * '$'` first, so a directive written one line low was invisible to the reader AND survived the
 * removal that was supposed to take the file out of every group it is in. */
function groupDirectivesOf(node: GroupNodeWire): readonly GroupAnnotationWire[] {
  return (node.annotations ?? []).filter(isGroupDirective)
}

