// Names and ids
// ---------------------------------------------------------------------------

/** A name as it is stored: trimmed, inner whitespace collapsed to single spaces. The directive's
 * arguments are whitespace-split on the way back in, so this is the only spelling that survives
 * a round trip, and normalising up front is what makes "what I typed" equal "what I get back". */
export function normaliseGroupName(raw: string): string {
  return raw.replace(/\s+/g, ' ').trim()
}

/** Why a name cannot be written, or null when it can. */
export function validateGroupName(name: string): string | null {
  const clean = normaliseGroupName(name)
  if (clean === '') return 'A group needs a name.'
  // A directive may sit in a block comment, where this sequence would end the comment early and
  // turn the rest of the name into JSON the engine refuses.
  if (clean.includes('*/')) return 'A group name cannot contain "*/".'
  return null
}

/** The words a name is written as, one argument each. */
function nameWords(name: string): string[] {
  return normaliseGroupName(name).split(' ')
}

/** A fresh id for a group called `name`: the name as a slug, suffixed when the slug is taken.
 *
 * Stable across renames by construction -- it is only ever computed here, at creation -- so the
 * id is a handle and not a second copy of the name. */
export function slugForGroup(name: string, taken: Iterable<string>): string {
  const used = new Set(taken)
  const base =
    normaliseGroupName(name)
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '') || 'group'
  if (!used.has(base)) return base
  for (let n = 2; n < 10_000; n++) {
    const candidate = `${base}-${String(n)}`
    if (!used.has(candidate)) return candidate
  }
  return `${base}-${String(Date.now())}`
}

export function groupNodeId(groupId: string): string {
  return `${GROUP_NODE_PREFIX}${groupId}`
}

/** The group id a synthetic node stands for, or null for an ordinary node. Stricter than the
 * prefix alone: the rest must be a valid group id, which no feature identifier's path is likely
 * to be, and which is what a caller then looks up anyway. */
export function groupIdOfNode(nodeId: string): string | null {
  if (!nodeId.startsWith(GROUP_NODE_PREFIX)) return null
  const rest = nodeId.slice(GROUP_NODE_PREFIX.length)
  return GROUP_ID_PATTERN.test(rest) ? rest : null
}

export function isGroupNodeId(nodeId: string): boolean {
  return groupIdOfNode(nodeId) !== null
}

