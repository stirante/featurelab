#!/usr/bin/env node
// extract-coverage.mjs -- writes generated/coverage.json from the engine's own coverage table.
//
// features/coverage.go is the single source of truth for which feature types this tool
// implements, how far, and what each gap means for a pack; features/coverage_test.go holds it
// against the live builder registry. The repo README deliberately refuses to copy the counts
// into prose because a copied list always drifts; the wiki's coverage page does copy them ("22
// fully, 5 partially") and is therefore one `featurelab types` away from being wrong. This
// script is how the site avoids the same trap: the coverage page, the per-type coverage badge
// and the features index all read this file, and this file is regenerated by the build.
//
// Usage:  node docs/site/tools/extract-coverage.mjs
// Needs:  the Go toolchain (it runs `go run ./cmd/featurelab types --json` at the repo root).
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const toolsDir = path.dirname(fileURLToPath(import.meta.url))
const siteDir = path.resolve(toolsDir, '..')
const repoRoot = path.resolve(siteDir, '..', '..')
const outPath = path.join(siteDir, 'generated', 'coverage.json')

const stdout = execFileSync('go', ['run', './cmd/featurelab', 'types', '--json'], {
  cwd: repoRoot,
  encoding: 'utf-8',
  maxBuffer: 16 * 1024 * 1024,
  stdio: ['ignore', 'pipe', 'inherit'],
})
const table = JSON.parse(stdout)
if (!table.summary || !Array.isArray(table.types)) {
  throw new Error('featurelab types --json did not return {summary, types}')
}
fs.mkdirSync(path.dirname(outPath), { recursive: true })
fs.writeFileSync(outPath, JSON.stringify(table, null, 2) + '\n')
const s = table.summary
console.log(
  `docs/site: coverage.json -- ${s.total} types: ${s.implemented} implemented, ${s.partial} partial, ` +
    `${s.missing} missing, ${s.outOfScope} out of scope`,
)
